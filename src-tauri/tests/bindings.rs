//! The checked-in `src/bindings.ts` is what the commands generate.

use std::path::Path;

use socketsweep_lib::specta_builder;
use specta_typescript::Typescript;

const HEADER: &str = "// Generated by tauri-specta from src-tauri/src/commands.rs and crates/gui-contract.\n// Do not edit by hand: a test in src-tauri fails if this file is stale.";

/// Run with `UPDATE_BINDINGS=1` to rewrite the file instead of checking it.
#[test]
fn checked_in_bindings_are_up_to_date() {
    let checked_in = Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/bindings.ts");
    let language = Typescript::default().header(HEADER);
    if std::env::var_os("UPDATE_BINDINGS").is_some() {
        specta_builder()
            .export(language, &checked_in)
            .expect("write src/bindings.ts");
        return;
    }
    let fresh_path =
        std::env::temp_dir().join(format!("socketsweep-bindings-{}.ts", std::process::id()));
    specta_builder()
        .export(language, &fresh_path)
        .expect("the commands export to TypeScript");
    let fresh = std::fs::read_to_string(&fresh_path).expect("read the export");
    let _ = std::fs::remove_file(&fresh_path);
    let current = std::fs::read_to_string(&checked_in).unwrap_or_default();
    assert!(
        current.replace("\r\n", "\n") == fresh.replace("\r\n", "\n"),
        "src/bindings.ts is stale. Regenerate it with \
         `UPDATE_BINDINGS=1 cargo test -p socketsweep --test bindings`."
    );
}
